// @ts-check
import { cpSync, existsSync, rmSync } from 'node:fs';
import path from 'node:path';

import starlight from '@astrojs/starlight';
import { defineConfig } from 'astro/config';
import mermaid from 'astro-mermaid';
import starlightTypeDoc, { typeDocSidebarGroup } from 'starlight-typedoc';

import { apiReference, docsRoot, exec, repoRoot } from './integrations/api-reference.mjs';

const isDev = process.argv.includes('dev');

// API reference sources. Each one joins the site once it exists, so the
// reference grows phase by phase as the adapters land.
const sources = {
  // Generated by napi-rs from the Rust source, including `///` doc comments.
  typescript: 'adapters/node/index.d.ts',
  // Maturin mixed layout: Python package with `.pyi` stubs for the extension.
  python: 'adapters/python/python/authfil',
  rust: 'crates',
};
const has = (source) => existsSync(path.join(repoRoot, source));

export default defineConfig({
  // Set by the GitHub Pages workflow; unset locally.
  site: process.env.DOCS_SITE_URL,
  base: process.env.DOCS_BASE || '/',
  trailingSlash: 'always',
  // Pages that moved when the site was reorganised, so old links keep working.
  redirects: {
    '/guides/getting-started/': '/get-started/development-setup/',
    '/guides/architecture/': '/concepts/architecture/',
    '/guides/contributing/': '/project/contributing/',
  },
  integrations: [
    mermaid({
      theme: 'neutral',
      autoTheme: true,
    }),
    apiReference({
      name: 'rust',
      source: sources.rust,
      watch: ['crates', 'adapters/node/src', 'adapters/python/src'],
      generate: async () => {
        await exec('cargo', ['doc', '--workspace', '--no-deps']);
        const out = path.join(docsRoot, 'public/api/rust');
        rmSync(out, { recursive: true, force: true });
        cpSync(path.join(repoRoot, 'target/doc'), out, { recursive: true });
      },
    }),
    apiReference({
      name: 'python',
      source: sources.python,
      watch: [sources.python],
      generate: () =>
        exec('uv', [
          'run', '--no-project', '--quiet', '--with', 'griffe>=2,<3',
          'python', 'docs/scripts/python_api.py',
          path.dirname(sources.python), path.basename(sources.python),
          'docs/src/content/docs/reference/python',
        ]),
    }),
    starlight({
      title: 'Authfil',
      description:
        'An open-source authentication and authorization library, written once in Rust and usable from any language.',
      lastUpdated: false,
      logo: {
        src: './src/assets/logo.png',
        alt: 'Authfil',
      },
      favicon: '/favicon.png',
      social: [
        { icon: 'github', label: 'GitHub', href: 'https://github.com/authfil/auth-fil' },
      ],
      editLink: {
        baseUrl: 'https://github.com/authfil/auth-fil/edit/main/docs/',
      },
      customCss: ['./src/styles/theme.css', './src/styles/mermaid-zoom.css', './src/styles/layout.css'],
      components: {
        Head: './src/components/Head.astro',
        SiteTitle: './src/components/SiteTitle.astro',
      },
      plugins: has(sources.typescript)
        ? [
            starlightTypeDoc({
              entryPoints: [path.join(repoRoot, sources.typescript)],
              tsconfig: path.join(docsRoot, 'typedoc.tsconfig.json'),
              output: 'reference/typescript',
              typeDoc: { name: 'authfil', readme: 'none' },
              sidebar: { label: 'TypeScript', collapsed: true },
              watch: isDev,
            }),
          ]
        : [],
      // Ordered like a reader's path through the docs: start, understand,
      // pick a language, then look things up.
      sidebar: [
        {
          label: 'Get started',
          items: ['get-started/introduction', 'get-started/development-setup'],
        },
        {
          label: 'Concepts',
          items: [
            'concepts/architecture',
            'concepts/sans-io-core',
            'concepts/crypto',
            'concepts/conformance',
          ],
        },
        {
          label: 'Adapters',
          items: [
            { label: 'Overview', slug: 'adapters' },
            'adapters/node',
            'adapters/python',
            'adapters/go',
            'adapters/java',
            'adapters/rust',
          ],
        },
        {
          label: 'Security',
          items: ['security/threat-models'],
        },
        {
          label: 'API reference',
          items: [
            'reference',
            ...(has(sources.typescript) ? [typeDocSidebarGroup] : []),
            ...(has(sources.python)
              ? [
                  {
                    label: 'Python',
                    collapsed: true,
                    items: [{ autogenerate: { directory: 'reference/python' } }],
                  },
                ]
              : []),
            { label: 'Rust (rustdoc)', link: '/api/rust/authfil_core/' },
          ],
        },
        {
          label: 'Project',
          items: [
            'project/roadmap',
            'project/contributing',
            'project/directory-conventions',
            'project/research',
            'project/credits',
            'project/sponsors',
          ],
        },
        {
          label: 'Decisions',
          collapsed: true,
          items: [{ autogenerate: { directory: 'decisions' } }],
        },
      ],
    }),
  ],
});
